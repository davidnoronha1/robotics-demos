/**
 * Curated manifest for the NVIDIA robotics graph.
 *
 * The fetch script (scripts/fetch-nvidia-projects.ts) reads this config, pulls
 * repo metadata + READMEs from the GitHub API, and emits
 * src/nvidia-graph/projects.data.json (committed, so the page works statically).
 *
 * Tune the org list, keyword filters, domain rules, and edges here.
 */

export interface DomainDef {
  id: string;
  label: string;
  color: string;
  // Lowercased substrings scored against name + description + topics.
  keywords: string[];
}

export interface OrgSource {
  org: string;
  // Pull every non-fork repo regardless of keyword match.
  includeAll?: boolean;
}

// Repos matched by keyword only must have at least this many stars to make the
// graph (allowlist and includeAll orgs bypass this). Keeps tiny experiments and
// tangentially-related research repos out of the map.
export const minAutoStars = 50;

export interface ManualNode {
  id: string;
  label: string;
  domain: string;
  description: string;
  homepage?: string;
}

export type EdgeType = "dependsOn" | "partOf" | "relatedTo";

export interface EdgeDef {
  source: string;
  target: string;
  type: EdgeType;
  // Relation strength, 0 to 1. Drives edge width/opacity and layout pull
  // (fcose ideal edge length) in the graph UI. Undefined -> neutral default
  // styling.
  score?: number;
}

export interface Config {
  domains: DomainDef[];
  orgs: OrgSource[];
  // owner/repo allowlist, guaranteed to be fetched even if keywords miss.
  include: string[];
  // owner/repo (or bare repo names) to skip.
  exclude: string[];
  // Lowercased substrings in name/description/topics that flag a repo as robotics-related.
  includeKeywords: string[];
  // Non-repo products that belong on the map regardless of a GitHub host.
  manual: ManualNode[];
  // Explicit domain assignments (by owner/repo) that beat keyword scoring.
  domainOverrides: Record<string, string>;
  // Org -> umbrella manual node: every repo in the org gets a partOf edge.
  orgProducts: Record<string, string>;
  edges: EdgeDef[];
  // Cap for stored README markdown, per repo.
  readmeMaxBytes: number;
  // Summary length in chars (surface copy in the side panel).
  summaryMaxChars: number;
}

